begin;

alter table public.mov_tareo rename to mov_tareo_importacion;
alter index public.mov_tareo_pkey rename to mov_tareo_importacion_pkey;
alter index public.mov_tareo_nro_parte_key rename to mov_tareo_importacion_nro_parte_key;
alter index public.mov_tareo_empresa_fecha_idx rename to mov_tareo_importacion_empresa_fecha_idx;
alter index public.mov_tareo_centro_fecha_idx rename to mov_tareo_importacion_centro_fecha_idx;
alter index public.mov_tareo_maquinaria_fecha_idx rename to mov_tareo_importacion_maquinaria_fecha_idx;

create table public.mov_tareo (
    id_mov_tareo bigint generated by default as identity primary key,
    nro_parte text not null unique,
    cod_cc bigint not null,
    cod_cc_maq bigint not null,
    hora numeric(10, 2) not null check (hora > 0),
    fecha_tareo date not null,
    etapa_tareo text,
    id_empresa bigint not null,
    cod_cc_pk bigint not null,
    cod_cc_pk_maq bigint not null,
    observacion text,
    estado smallint not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint mov_tareo_empresa_fkey
        foreign key (id_empresa)
        references public."Dim_Empresa"(id_empresa),
    constraint mov_tareo_centro_costo_fkey
        foreign key (cod_cc_pk)
        references public.dim_centro_costo(cod_cc_pk),
    constraint mov_tareo_maquinaria_fkey
        foreign key (cod_cc_pk_maq)
        references public.dim_centro_costo(cod_cc_pk)
);

comment on table public.mov_tareo is
    'Horas de maquinaria validadas por centro de costo operativo y maquinaria.';
comment on column public.mov_tareo.cod_cc_pk is
    'Centro de costo operativo al que se imputan las horas.';
comment on column public.mov_tareo.cod_cc_pk_maq is
    'Centro de costo de la maquinaria que realizó el tareo.';
comment on column public.mov_tareo.nro_parte is
    'Identificador del registro fuente, usado para evitar duplicados al importar.';

create index mov_tareo_empresa_fecha_idx
    on public.mov_tareo (id_empresa, fecha_tareo);
create index mov_tareo_centro_fecha_idx
    on public.mov_tareo (cod_cc_pk, fecha_tareo);
create index mov_tareo_maquinaria_fecha_idx
    on public.mov_tareo (cod_cc_pk_maq, fecha_tareo);

alter table public.mov_tareo enable row level security;

alter table public.mov_tareo_importacion add column aplicado_at timestamptz;

comment on table public.mov_tareo_importacion is
    'Conserva filas originales importadas, incluso las que fallan validaciones; solo los registros válidos pasan a mov_tareo.';
alter table public.mov_tareo_importacion enable row level security;

commit;
