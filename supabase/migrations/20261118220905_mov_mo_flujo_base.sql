begin;

create table public.mov_mo (
  id_mov_mo bigint generated by default as identity primary key,
  id_empresa bigint not null references public."Dim_Empresa" (id_empresa),
  cod_cc_pk bigint not null references public.dim_centro_costo (cod_cc_pk),
  cod_cc bigint not null,
  cod_labor bigint not null references public."Dim_Labor" ("Id_Lab"),
  labor_scire text not null,
  imp_labor_sol numeric not null,
  ess_labor_sol numeric,
  fec_labor date not null,
  etapa_costo text,
  obs text,
  estado smallint not null default 1 check (estado in (0, 1)),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.mov_mo_proceso (
  id_mov_mo bigint generated by default as identity primary key,
  id_empresa bigint,
  cod_cc_pk bigint,
  cod_cc bigint,
  cod_labor bigint,
  labor_scire text,
  imp_labor_sol numeric,
  ess_labor_sol numeric,
  fec_labor date,
  etapa_costo text,
  obs text,
  estado smallint not null default 1 check (estado in (0, 1)),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.mov_mo_pendiente (
  id_mov_mo bigint generated by default as identity primary key,
  id_empresa bigint,
  cod_cc_pk bigint,
  cod_cc bigint,
  cod_labor bigint,
  labor_scire text,
  imp_labor_sol numeric,
  ess_labor_sol numeric,
  fec_labor date,
  etapa_costo text,
  obs text,
  estado smallint not null default 1 check (estado in (0, 1)),
  estado_validacion text not null default 'PENDIENTE'
    check (estado_validacion in ('PENDIENTE', 'VALIDO', 'OBSERVADO')),
  errores_validacion jsonb not null default '[]'::jsonb
    check (jsonb_typeof(errores_validacion) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.mov_mo is 'Registros de mano de obra validados y procesados.';
comment on table public.mov_mo_proceso is 'Filas importadas en proceso de validación para Mano de Obra.';
comment on table public.mov_mo_pendiente is 'Filas de Mano de Obra con observaciones pendientes de resolver.';
comment on column public.mov_mo.estado is 'Estado del registro: 1 activo, 0 inactivo.';
comment on column public.mov_mo_proceso.estado is 'Estado del registro: 1 activo, 0 inactivo.';
comment on column public.mov_mo_pendiente.estado is 'Estado del registro: 1 activo, 0 inactivo.';
comment on column public.mov_mo_proceso.ess_labor_sol is 'Acepta NULL cuando el archivo fuente indica que no aplica.';
comment on column public.mov_mo_pendiente.errores_validacion is 'Lista de observaciones detectadas durante la validación.';

create index mov_mo_empresa_fecha_idx on public.mov_mo (id_empresa, fec_labor);
create index mov_mo_centro_fecha_idx on public.mov_mo (cod_cc_pk, fec_labor);
create index mov_mo_labor_fecha_idx on public.mov_mo (cod_labor, fec_labor);
create index mov_mo_proceso_empresa_fecha_idx on public.mov_mo_proceso (id_empresa, fec_labor);
create index mov_mo_pendiente_empresa_fecha_idx on public.mov_mo_pendiente (id_empresa, fec_labor);

alter table public.mov_mo enable row level security;
alter table public.mov_mo_proceso enable row level security;
alter table public.mov_mo_pendiente enable row level security;

revoke all on table public.mov_mo, public.mov_mo_proceso, public.mov_mo_pendiente from public, anon, authenticated;
grant select, insert, update, delete on table public.mov_mo, public.mov_mo_proceso, public.mov_mo_pendiente to authenticated;

create policy mov_mo_select_admin on public.mov_mo for select to authenticated using ((select private.is_admin()));
create policy mov_mo_insert_admin on public.mov_mo for insert to authenticated with check ((select private.is_admin()));
create policy mov_mo_update_admin on public.mov_mo for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy mov_mo_delete_admin on public.mov_mo for delete to authenticated using ((select private.is_admin()));

create policy mov_mo_proceso_select_admin on public.mov_mo_proceso for select to authenticated using ((select private.is_admin()));
create policy mov_mo_proceso_insert_admin on public.mov_mo_proceso for insert to authenticated with check ((select private.is_admin()));
create policy mov_mo_proceso_update_admin on public.mov_mo_proceso for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy mov_mo_proceso_delete_admin on public.mov_mo_proceso for delete to authenticated using ((select private.is_admin()));

create policy mov_mo_pendiente_select_admin on public.mov_mo_pendiente for select to authenticated using ((select private.is_admin()));
create policy mov_mo_pendiente_insert_admin on public.mov_mo_pendiente for insert to authenticated with check ((select private.is_admin()));
create policy mov_mo_pendiente_update_admin on public.mov_mo_pendiente for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy mov_mo_pendiente_delete_admin on public.mov_mo_pendiente for delete to authenticated using ((select private.is_admin()));

create or replace function private.set_mov_mo_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
revoke all on function private.set_mov_mo_updated_at() from public, anon, authenticated, service_role;

create trigger trg_mov_mo_updated_at before update on public.mov_mo
for each row execute function private.set_mov_mo_updated_at();
create trigger trg_mov_mo_proceso_updated_at before update on public.mov_mo_proceso
for each row execute function private.set_mov_mo_updated_at();
create trigger trg_mov_mo_pendiente_updated_at before update on public.mov_mo_pendiente
for each row execute function private.set_mov_mo_updated_at();

commit;
