begin;

create table public.mov_tareo_historial (
    id_historial bigint generated by default as identity primary key,
    id_mov_tareo bigint references public.mov_tareo(id_mov_tareo) on delete set null,
    id_empresa bigint not null references public."Dim_Empresa"(id_empresa),
    nro_parte text not null,
    campos_modificados text[] not null,
    datos_anteriores jsonb not null,
    datos_nuevos jsonb not null,
    cambio_por uuid references auth.users(id) on delete set null,
    cambio_at timestamptz not null default now()
);

comment on table public.mov_tareo_historial is
    'Auditoría de cambios manuales aplicados a los movimientos de Tareo.';
create index mov_tareo_historial_empresa_parte_idx
    on public.mov_tareo_historial (id_empresa, nro_parte, cambio_at desc);

alter table public.mov_tareo_historial enable row level security;
revoke all on table public.mov_tareo_historial from anon, public, authenticated;
grant select on table public.mov_tareo_historial to authenticated;

create policy mov_tareo_historial_select_autorizado
on public.mov_tareo_historial
for select to authenticated
using (
    (select private.is_admin())
    or (
        (select private.can_access_module('MOV_TAREO', 'QUERY'))
        and exists (
            select 1
            from public.usuario_empresa ue
            join public.usuarios u on u.id_usuario = ue.id_usuario
            where ue.id_empresa = mov_tareo_historial.id_empresa
              and ue.estado is true
              and u.auth_user_id = (select auth.uid())
              and u.estado::text = 'ACTIVO'
        )
    )
);

create or replace function private.audit_mov_tareo_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
    v_campos text[];
begin
    select array_agg(anterior.key order by anterior.key)
    into v_campos
    from jsonb_each(to_jsonb(old)) as anterior(key, value)
    join jsonb_each(to_jsonb(new)) as nuevo(key, value) using (key)
    where anterior.value is distinct from nuevo.value
      and anterior.key <> 'updated_at';

    if coalesce(array_length(v_campos, 1), 0) > 0 then
        insert into public.mov_tareo_historial (
            id_mov_tareo,
            id_empresa,
            nro_parte,
            campos_modificados,
            datos_anteriores,
            datos_nuevos,
            cambio_por
        )
        values (
            new.id_mov_tareo,
            new.id_empresa,
            new.nro_parte,
            v_campos,
            to_jsonb(old),
            to_jsonb(new),
            auth.uid()
        );
    end if;

    return new;
end;
$function$;

revoke all on function private.audit_mov_tareo_update() from public, anon, authenticated;

create trigger mov_tareo_audit_update
after update on public.mov_tareo
for each row execute function private.audit_mov_tareo_update();

commit;
