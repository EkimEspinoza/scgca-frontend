-- Fase 1: crea las tablas vacías del catálogo y asignaciones.
-- No carga datos ni modifica políticas de tablas de negocio.

create table public.modulos (
    id_modulo bigint generated by default as identity primary key,
    codigo text not null unique,
    nombre text not null,
    grupo text not null,
    ruta text,
    orden integer not null default 0,
    estado boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint modulos_codigo_formato check (codigo ~ '^[A-Z][A-Z0-9_]*$')
);

create table public.usuario_modulo (
    id_usuario_modulo bigint generated by default as identity primary key,
    id_usuario bigint not null references public.usuarios(id_usuario),
    id_modulo bigint not null references public.modulos(id_modulo),
    nivel text not null check (nivel in ('QUERY', 'READER')),
    estado boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint usuario_modulo_unico unique (id_usuario, id_modulo)
);

create index usuario_modulo_usuario_activo_idx
    on public.usuario_modulo (id_usuario, id_modulo)
    where estado is true;

alter table public.modulos enable row level security;
alter table public.usuario_modulo enable row level security;

grant select, insert, update, delete on public.modulos to authenticated;
grant select, insert, update, delete on public.usuario_modulo to authenticated;
grant usage, select on sequence public.modulos_id_modulo_seq to authenticated;
grant usage, select on sequence public.usuario_modulo_id_usuario_modulo_seq to authenticated;

create policy modulos_ver_catalogo_activo
    on public.modulos for select to authenticated
    using (
        (estado is true and (select private.get_my_permission()) is not null)
        or (select private.is_admin())
    );

create policy modulos_admin_insertar
    on public.modulos for insert to authenticated
    with check ((select private.is_admin()));

create policy modulos_admin_actualizar
    on public.modulos for update to authenticated
    using ((select private.is_admin()))
    with check ((select private.is_admin()));

create policy modulos_admin_eliminar
    on public.modulos for delete to authenticated
    using ((select private.is_admin()));

create policy usuario_modulo_ver_propias_o_admin
    on public.usuario_modulo for select to authenticated
    using (
        (select private.is_admin())
        or exists (
            select 1 from public.usuarios u
            where u.id_usuario = usuario_modulo.id_usuario
              and u.auth_user_id = (select auth.uid())
              and u.estado = 'ACTIVO'
              and (select private.get_my_permission()) is not null
        )
    );

create policy usuario_modulo_admin_insertar
    on public.usuario_modulo for insert to authenticated
    with check ((select private.is_admin()));

create policy usuario_modulo_admin_actualizar
    on public.usuario_modulo for update to authenticated
    using ((select private.is_admin()))
    with check ((select private.is_admin()));

create policy usuario_modulo_admin_eliminar
    on public.usuario_modulo for delete to authenticated
    using ((select private.is_admin()));
