begin;

create table public.mov_tareo (
    id_mov_tareo bigint generated by default as identity primary key,
    nro_parte text not null unique,
    cod_cc bigint not null,
    cod_cc_maq bigint not null,
    hora numeric(10, 2) not null check (hora > 0),
    fecha_tareo date not null,
    etapa_tareo text,
    id_empresa bigint not null references public."Dim_Empresa"(id_empresa),
    cod_cc_pk bigint not null,
    cod_cc_pk_maq bigint not null,
    observacion text,
    estado smallint not null,
    estado_validacion text not null default 'PENDIENTE'
        check (estado_validacion in ('PENDIENTE', 'VALIDO', 'OBSERVADO')),
    errores_validacion jsonb not null default '[]'::jsonb
        check (jsonb_typeof(errores_validacion) = 'array'),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

comment on table public.mov_tareo is
    'Importación y registro de horas de maquinaria por centro de costo operativo. NRO_PARTE identifica el registro fuente y permite cargas incrementales.';
comment on column public.mov_tareo.estado is
    'Valor original ESTADO del archivo importado; su catálogo semántico queda pendiente de confirmar.';
comment on column public.mov_tareo.estado_validacion is
    'Resultado de validación de catálogos y reglas de negocio para la carga.';
comment on column public.mov_tareo.errores_validacion is
    'Lista de observaciones de validación; permite conservar filas que requieren corrección.';

create index mov_tareo_empresa_fecha_idx
    on public.mov_tareo (id_empresa, fecha_tareo);
create index mov_tareo_centro_fecha_idx
    on public.mov_tareo (cod_cc_pk, fecha_tareo);
create index mov_tareo_maquinaria_fecha_idx
    on public.mov_tareo (cod_cc_pk_maq, fecha_tareo);

alter table public.mov_tareo enable row level security;

commit;
